import { NotFoundException } from '@nestjs/common';
import { PrismaService } from 'src/infra/prisma/prisma.service';
import { ForecastSnapshotRepository } from 'src/infra/repositories/works/schedule/forecastSnapshotRepository';
import { CreateForecastSnapshotDTO } from 'src/interface/dtos/forecastSnapshotDTO';
import { beforeEach, describe, expect, it, vi } from 'vitest';

// ==========================================================
// 🧪 mocks e fixtures
// ==========================================================
const mockPrisma = {
  forecast_snapshot: {
    create: vi.fn(),
    delete: vi.fn(),
    findUnique: vi.fn(),
    findMany: vi.fn(),
  },
};

const filtros = { regiao: 'SUL', ano: 2026 };
const diario = [{ data: '2026-11-01', valor: 100 }];
const grupo = [{ grupo: 'A', total: 300 }];

const makeDto = (overrides: Partial<CreateForecastSnapshotDTO> = {}) =>
  ({
    filtros,
    diario,
    grupo,
    ...overrides,
  }) as unknown as CreateForecastSnapshotDTO;

const makeSnapshot = (overrides: Record<string, unknown> = {}) => ({
  id: 1,
  gerado_em: new Date('2026-11-01T10:00:00Z'),
  filtros,
  diario,
  grupo,
  ...overrides,
});

describe('ForecastSnapshotRepository', () => {
  let repository: ForecastSnapshotRepository;

  beforeEach(() => {
    vi.clearAllMocks();
    repository = new ForecastSnapshotRepository(
      mockPrisma as unknown as PrismaService,
    );
  });

  // ==========================================================
  // ➕ create
  // ==========================================================
  describe('create', () => {
    it('should call create with filtros, diario and grupo', async () => {
      mockPrisma.forecast_snapshot.create.mockResolvedValueOnce(makeSnapshot());

      await repository.create(makeDto());

      expect(mockPrisma.forecast_snapshot.create).toHaveBeenCalledTimes(1);
      expect(mockPrisma.forecast_snapshot.create).toHaveBeenCalledWith({
        data: { filtros, diario, grupo },
      });
    });

    it.each([
      ['undefined', undefined],
      ['null', null],
    ])('should default filtros to {} when it is %s', async (_label, value) => {
      mockPrisma.forecast_snapshot.create.mockResolvedValueOnce(makeSnapshot());

      await repository.create(makeDto({ filtros: value as any }));

      expect(mockPrisma.forecast_snapshot.create).toHaveBeenCalledWith({
        data: { filtros: {}, diario, grupo },
      });
    });

    it('should keep an empty filtros object as is', async () => {
      mockPrisma.forecast_snapshot.create.mockResolvedValueOnce(makeSnapshot());

      await repository.create(makeDto({ filtros: {} as any }));

      expect(mockPrisma.forecast_snapshot.create).toHaveBeenCalledWith({
        data: { filtros: {}, diario, grupo },
      });
    });

    it('should not send id or gerado_em (generated by the database)', async () => {
      mockPrisma.forecast_snapshot.create.mockResolvedValueOnce(makeSnapshot());

      await repository.create(makeDto());

      const { data } = mockPrisma.forecast_snapshot.create.mock.calls[0][0];
      expect(Object.keys(data).sort()).toEqual(['diario', 'filtros', 'grupo']);
    });

    it('should resolve to undefined', async () => {
      mockPrisma.forecast_snapshot.create.mockResolvedValueOnce(makeSnapshot());

      await expect(repository.create(makeDto())).resolves.toBeUndefined();
    });

    it('should propagate database errors', async () => {
      mockPrisma.forecast_snapshot.create.mockRejectedValueOnce(
        new Error('DB error'),
      );

      await expect(repository.create(makeDto())).rejects.toThrow('DB error');
    });
  });

  // ==========================================================
  // 🗑️ delete
  // ==========================================================
  describe('delete', () => {
    it('should call delete with the correct id', async () => {
      mockPrisma.forecast_snapshot.delete.mockResolvedValueOnce(makeSnapshot());

      await repository.delete(1);

      expect(mockPrisma.forecast_snapshot.delete).toHaveBeenCalledWith({
        where: { id: 1 },
      });
    });

    it('should resolve to undefined', async () => {
      mockPrisma.forecast_snapshot.delete.mockResolvedValueOnce(makeSnapshot());

      await expect(repository.delete(1)).resolves.toBeUndefined();
    });

    it('should throw NotFoundException if id not found (P2025)', async () => {
      mockPrisma.forecast_snapshot.delete.mockRejectedValueOnce({
        code: 'P2025',
      });

      const promise = repository.delete(99);

      await expect(promise).rejects.toBeInstanceOf(NotFoundException);
      await expect(promise).rejects.toThrow(
        'Snapshot com ID 99 não encontrado',
      );
    });

    it('should rethrow other database errors unchanged', async () => {
      const error = new Error('DB error');
      mockPrisma.forecast_snapshot.delete.mockRejectedValueOnce(error);

      await expect(repository.delete(1)).rejects.toBe(error);
    });
  });

  // ==========================================================
  // 🔎 get
  // ==========================================================
  describe('get', () => {
    it('should call findUnique with the correct id', async () => {
      mockPrisma.forecast_snapshot.findUnique.mockResolvedValueOnce(
        makeSnapshot(),
      );

      await repository.get(1);

      expect(mockPrisma.forecast_snapshot.findUnique).toHaveBeenCalledWith({
        where: { id: 1 },
      });
    });

    it('should return the snapshot with all fields', async () => {
      const snapshot = makeSnapshot();
      mockPrisma.forecast_snapshot.findUnique.mockResolvedValueOnce(snapshot);

      const result = await repository.get(1);

      expect(result).toEqual({
        id: 1,
        gerado_em: snapshot.gerado_em,
        filtros,
        diario,
        grupo,
      });
    });

    it('should keep extra columns returned by the database (spread)', async () => {
      mockPrisma.forecast_snapshot.findUnique.mockResolvedValueOnce(
        makeSnapshot({ criado_por: 'user-1' }),
      );

      const result = await repository.get(1);

      expect(result).toHaveProperty('criado_por', 'user-1');
    });

    it('should throw NotFoundException if snapshot does not exist', async () => {
      mockPrisma.forecast_snapshot.findUnique.mockResolvedValueOnce(null);

      const promise = repository.get(99);

      await expect(promise).rejects.toBeInstanceOf(NotFoundException);
      await expect(promise).rejects.toThrow(
        'Snapshot com ID 99 não encontrado',
      );
    });

    it('should propagate database errors', async () => {
      mockPrisma.forecast_snapshot.findUnique.mockRejectedValueOnce(
        new Error('DB error'),
      );

      await expect(repository.get(1)).rejects.toThrow('DB error');
    });
  });

  // ==========================================================
  // 📋 getAll
  // ==========================================================
  describe('getAll', () => {
    const select = { id: true, gerado_em: true, filtros: true };

    it('should call findMany with the date filter and the correct select', async () => {
      mockPrisma.forecast_snapshot.findMany.mockResolvedValueOnce([]);
      const where = {
        gerado_em: {
          gte: new Date('2026-11-01T00:00:00Z'),
          lte: new Date('2026-11-30T23:59:59Z'),
        },
      };

      await repository.getAll(where);

      expect(mockPrisma.forecast_snapshot.findMany).toHaveBeenCalledWith({
        where,
        select,
      });
    });

    it('should call findMany with an empty where when no filter is given', async () => {
      mockPrisma.forecast_snapshot.findMany.mockResolvedValueOnce([]);

      await repository.getAll({});

      expect(mockPrisma.forecast_snapshot.findMany).toHaveBeenCalledWith({
        where: {},
        select,
      });
    });

    it('should not select diario nor grupo (heavy fields)', async () => {
      mockPrisma.forecast_snapshot.findMany.mockResolvedValueOnce([]);

      await repository.getAll({});

      const args = mockPrisma.forecast_snapshot.findMany.mock.calls[0][0];
      expect(args.select).not.toHaveProperty('diario');
      expect(args.select).not.toHaveProperty('grupo');
    });

    it('should map snapshots to id, gerado_em and filtros', async () => {
      const first = makeSnapshot({ id: 1 });
      const second = makeSnapshot({
        id: 2,
        gerado_em: new Date('2026-11-02T10:00:00Z'),
      });
      mockPrisma.forecast_snapshot.findMany.mockResolvedValueOnce([
        first,
        second,
      ]);

      const result = await repository.getAll({});

      expect(result).toEqual([
        { id: 1, gerado_em: first.gerado_em, filtros },
        { id: 2, gerado_em: second.gerado_em, filtros },
      ]);
    });

    it('should drop any extra field returned by the database', async () => {
      mockPrisma.forecast_snapshot.findMany.mockResolvedValueOnce([
        makeSnapshot(),
      ]);

      const [item] = await repository.getAll({});

      expect(Object.keys(item).sort()).toEqual(['filtros', 'gerado_em', 'id']);
    });

    it('should return an empty array when there are no snapshots', async () => {
      mockPrisma.forecast_snapshot.findMany.mockResolvedValueOnce([]);

      await expect(repository.getAll({})).resolves.toEqual([]);
    });

    it('should preserve the order returned by the database', async () => {
      mockPrisma.forecast_snapshot.findMany.mockResolvedValueOnce([
        makeSnapshot({ id: 3 }),
        makeSnapshot({ id: 1 }),
        makeSnapshot({ id: 2 }),
      ]);

      const result = await repository.getAll({});

      expect(result.map((s) => s.id)).toEqual([3, 1, 2]);
    });

    it('should propagate database errors', async () => {
      mockPrisma.forecast_snapshot.findMany.mockRejectedValueOnce(
        new Error('DB error'),
      );

      await expect(repository.getAll({})).rejects.toThrow('DB error');
    });
  });
});
